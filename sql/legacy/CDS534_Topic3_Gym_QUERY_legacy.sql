use gym;

SELECT LIST.MID,LIST.NAME,ID.CLASS_NUMBER
FROM MEMBER AS LIST
JOIN    
  (SELECT COUNT(CLASS_ID) AS CLASS_NUMBER,MID
  FROM ENROLLMENT 
  WHERE IS_CANCELED !=TRUE
  GROUP BY MID
  HAVING CLASS_NUMBER>3) AS ID
ON ID.MID=LIST.MID;


SELECT TRAIN.TID,TRAIN.NAME,CLASS.CLASS_NUMBER
FROM TRAINER AS TRAIN
LEFT JOIN 
    (SELECT COUNT(CLASS_ID) AS CLASS_NUMBER,TRAINER_ID
     FROM CLASS 
     GROUP BY TRAINER_ID) AS CLASS
ON TRAIN.TID=CLASS.TRAINER_ID;

SELECT M_MT.MID,M_MT.MEMBERSHIP_ID,M_MT.TYPE,M_MT.NAME,C.CHECK_NUM
FROM
(SELECT MT.MEMBERSHIP_ID ,MT.TYPE,M.NAME,M.MID
FROM MEMBERSHIP AS MT
JOIN MEMBER AS M
ON MT.MEMBERSHIP_ID=M.MEMBERSHIP_ID) AS M_MT
JOIN (SELECT COUNT(CHECKIN_ID) AS CHECK_NUM,MID FROM CHECKIN GROUP BY MID) AS C
ON C.MID=M_MT.MID
ORDER BY CHECK_NUM DESC
