--  Section 2 : DDL

-- 1) Membership 
CREATE TABLE Membership (
    membership_id  INT          NOT NULL AUTO_INCREMENT  COMMENT 'membership plan id (PK)',
    type           VARCHAR(40)  NOT NULL                 COMMENT 'plan type: term / audience, e.g. Annual / Student',
    PRIMARY KEY (membership_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='membership plan (ER: Membership)';

-- 2) Member 
CREATE TABLE Member (
    mid            INT          NOT NULL AUTO_INCREMENT  COMMENT 'member id (PK)',
    name           VARCHAR(40)  NOT NULL                 COMMENT 'member full name',
    membership_id  INT          NOT NULL                 COMMENT 'FK -> Membership (plan purchased)',
    PRIMARY KEY (mid),
    KEY idx_member_membership (membership_id),
    CONSTRAINT fk_member_membership FOREIGN KEY (membership_id)
        REFERENCES Membership (membership_id)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='member (ER: Member)';

-- 3) Trainer 
CREATE TABLE Trainer (
    tid   INT          NOT NULL AUTO_INCREMENT  COMMENT 'trainer id (PK)',
    name  VARCHAR(40)  NOT NULL                 COMMENT 'trainer full name',
    PRIMARY KEY (tid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='trainer (ER: Trainer)';

-- 4) Class
CREATE TABLE Class (
    class_id    INT          NOT NULL AUTO_INCREMENT  COMMENT 'class id (PK)',
    name        VARCHAR(60)  NOT NULL                 COMMENT 'class name',
    trainer_id  INT          NOT NULL                 COMMENT 'FK -> Trainer (instructor)',
    PRIMARY KEY (class_id),
    KEY idx_class_trainer (trainer_id),
    CONSTRAINT fk_class_trainer FOREIGN KEY (trainer_id)
        REFERENCES Trainer (tid)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='group class (ER: Class)';

-- 5) CheckIn 
CREATE TABLE CheckIn (
    checkin_id  INT       NOT NULL AUTO_INCREMENT               COMMENT 'check-in id (PK)',
    mid         INT       NOT NULL                              COMMENT 'FK -> Member',
    time        DATETIME  NOT NULL DEFAULT CURRENT_TIMESTAMP    COMMENT 'check-in timestamp',
    PRIMARY KEY (checkin_id),
    KEY idx_checkin_mid_time (mid, time),
    CONSTRAINT fk_checkin_member FOREIGN KEY (mid)
        REFERENCES Member (mid)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='gym check-in (ER: CheckIn)';

-- 6) Enrollment 

CREATE TABLE Enrollment (
    mid          INT         NOT NULL                            COMMENT 'FK -> Member (composite PK, part 1)',
    class_id     INT         NOT NULL                            COMMENT 'FK -> Class  (composite PK, part 2)',
    enroll_time  DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP  COMMENT 'enrollment timestamp (relationship attribute)',
    is_canceled  TINYINT(1)  NOT NULL DEFAULT 0                  COMMENT 'cancelled flag: 0 = active, 1 = cancelled (relationship attribute)',
    PRIMARY KEY (mid, class_id),
    KEY idx_enroll_class (class_id),
    CONSTRAINT ck_enroll_canceled CHECK (is_canceled IN (0,1)),
    CONSTRAINT fk_enroll_member FOREIGN KEY (mid)
        REFERENCES Member (mid)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_enroll_class FOREIGN KEY (class_id)
        REFERENCES Class (class_id)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='enrollment (ER: Enrollment, resolves Member<->Class N:M)';


