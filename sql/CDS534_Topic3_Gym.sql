--  Section 4 : verification queries

SELECT TABLE_NAME AS tbl, ENGINE AS engine, TABLE_COLLATION AS collation
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = 'cds534_gym' AND TABLE_TYPE = 'BASE TABLE'
ORDER BY tbl;

SELECT 'Membership' AS tbl, COUNT(*) AS rows_cnt FROM Membership
UNION ALL SELECT 'Member', COUNT(*) FROM Member
UNION ALL SELECT 'Trainer', COUNT(*) FROM Trainer
UNION ALL SELECT 'Class', COUNT(*) FROM Class
UNION ALL SELECT 'CheckIn', COUNT(*) FROM CheckIn
UNION ALL SELECT 'Enrollment', COUNT(*) FROM Enrollment
;

SELECT ms.membership_id, ms.type, COUNT(m.mid) AS members
FROM Membership ms LEFT JOIN Member m ON m.membership_id = ms.membership_id
GROUP BY ms.membership_id, ms.type
HAVING members = 0;

SELECT t.tid, t.name, COUNT(c.class_id) AS classes
FROM Trainer t LEFT JOIN Class c ON c.trainer_id = t.tid
GROUP BY t.tid, t.name
HAVING classes = 0;

SELECT c.class_id, c.name,
       COUNT(e.mid) AS total_enroll,
       COALESCE(SUM(CASE WHEN e.is_canceled = 0 THEN 1 ELSE 0 END), 0) AS active_enroll
FROM Class c LEFT JOIN Enrollment e ON e.class_id = c.class_id
GROUP BY c.class_id, c.name
HAVING total_enroll = 0 OR active_enroll = 0;

SELECT m.mid, m.name, COUNT(ci.checkin_id) AS checkins
FROM Member m LEFT JOIN CheckIn ci ON ci.mid = m.mid
GROUP BY m.mid, m.name
HAVING checkins = 0;

SELECT is_canceled, COUNT(*) AS rows_cnt FROM Enrollment GROUP BY is_canceled;

-- Q1
SELECT m.name, COUNT(e.class_id) AS classes
FROM Member m JOIN Enrollment e ON e.mid = m.mid
WHERE e.is_canceled = 0
GROUP BY m.mid, m.name
HAVING COUNT(e.class_id) > 3
ORDER BY classes DESC, m.mid;

-- Q2 
SELECT t.name, COUNT(c.class_id) AS classes
FROM Trainer t LEFT JOIN Class c ON c.trainer_id = t.tid
GROUP BY t.tid, t.name
ORDER BY classes DESC, t.tid;

--  Q3 
SELECT ms.type, COUNT(ci.checkin_id) AS checkins
FROM Membership ms
JOIN Member m    ON m.membership_id = ms.membership_id
JOIN CheckIn ci  ON ci.mid = m.mid
GROUP BY ms.membership_id, ms.type
ORDER BY checkins DESC;

